    void tapTempo()
    {
        const double now = Time::getMillisecondCounterHiRes();
        if (taps.isEmpty() || now - taps.getLast() > 2000) taps.clear();
        taps.add (now);
        if (taps.size() > 5) taps.remove (0);
        if (taps.size() >= 2)
            bpm.set (60000.0 * (taps.size() - 1) / (taps.getLast() - taps.getFirst()));
    }

